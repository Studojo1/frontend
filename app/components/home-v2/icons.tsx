import type { ReactNode } from "react";

// The homepage's icons, drawn exactly as in the design prototype (hp/v2.html): 24 by 24, a 2 px round stroke in the
// text colour, always decorative (aria-hidden). Their size comes from home-v2.css unless `size` is given.

type IconProps = {
  /** Width and height in px (the prototype set it only on the hero chips, buttons and FAQ plus). */
  size?: number;
  /** Stroke width, 2 unless given. */
  sw?: number;
  /** The FAQ plus has round caps but no line join, as in the prototype. */
  noJoin?: boolean;
  className?: string;
};

function Svg({ size, sw = 2, noJoin = false, className, children }: IconProps & { children: ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={sw}
      strokeLinecap="round"
      strokeLinejoin={noJoin ? undefined : "round"}
      aria-hidden="true"
      className={className}
    >
      {children}
    </svg>
  );
}

